"""Generate a concise project landing page from metadata and discovered examples."""

import argparse
import html
import runpy
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def project(root=ROOT):
    metadata = tomllib.loads((root / "pyproject.toml").read_text())
    name = metadata["project"]["name"]
    package = name.replace("-", "_")
    launcher = root / "src" / package / "examples" / "__main__.py"
    examples = runpy.run_path(str(launcher))["discover"]()
    return metadata["project"], package, examples


def make_readme(root=ROOT, *, require_videos=False):
    metadata, package, examples = project(root)
    if not (root / "docs" / "method.md").is_file():
        raise ValueError("docs/method.md must explain the implemented method and cite its papers")
    text = [
        "<!-- Generated by tools/build_readme.py; edit project metadata, example docstrings or the generator. -->",
        f"# {metadata['name']}\n",
        metadata["description"] + ".\n",
        "FEM, cutting, needle coupling and prepared assets are included in this repository.\n"
        "No sibling solver checkout or source dataset is required to run the bundled examples.\n",
        "## Quickstart\n",
        "From this directory:\n",
        "```bash\n./docker/build.sh\n./docker/run.sh --list\n./docker/run.sh                 # Choose an example interactively.\n./docker/run.sh fem_phantom_cut # Full-pad cutting and spring grips.\n```\n",
        "Or use Python 3.12 locally:\n",
        f"```bash\nuv sync --locked --extra examples\nuv run --locked python -m {package}.examples\n```\n",
        "Run a specific example by appending its name; append `--help` for its options.\n"
        "See [setup and controls](docs/usage.md) for complete instructions.\n",
        "## Requirements\n",
        "- Linux x86-64 or ARM64; Python 3.12 and the locked dependencies.\n"
        "- CUDA: an NVIDIA driver compatible with the locked CUDA 13 Warp wheel; Docker also needs NVIDIA Container Toolkit.\n"
        "- Interactive viewing: X11 and a readable `XAUTHORITY` file.\n"
        "- CPU/headless runs: `./docker/run.sh --cpu --headless <example>`; full-pad scenes can be slow.\n",
        "## Examples\n",
        "Examples are discovered from their modules. Click a preview to open the recorded MP4.\n",
    ]
    cells = []
    for example, (description, _, module) in examples.items():
        media = root / "docs" / "media"
        clip = media / f"{example}.mp4"
        preview = next(
            (media / f"{example}{ext}" for ext in (".jpg", ".gif") if (media / f"{example}{ext}").is_file()), None
        )
        source = "src/" + package + "/examples/" + module.replace(".", "/") + ".py"
        cell = f"**[{example}]({source})**<br>{html.escape(description)}<br>"
        if clip.is_file() and preview:
            cell += f'<a href="docs/media/{clip.name}"><img src="docs/media/{preview.name}" width="300" alt="{html.escape(description, quote=True)}"></a><br>'
        elif require_videos:
            raise ValueError(f"Missing video or preview for {example}")
        else:
            cell += "Video not recorded yet.<br>"
        cell += f"`./docker/run.sh {example}`"
        cells.append(cell.replace("|", "&#124;"))
    text.append("| Example | Example |\n| --- | --- |")
    text.extend(f"| {cells[i]} | {cells[i + 1] if i + 1 < len(cells) else ''} |" for i in range(0, len(cells), 2))
    text.extend(
        [
            "\nThe pad and needle examples advance physical simulation. `fem_dvrk` replays measured\n"
            "da Vinci Research Kit motion; `fem_versius` previews generated motion with labeled dVRK\n"
            "placeholder videos. Both viewing scenes have static tissue. Movie playback rate is not live FPS;\n"
            "loaded needle handling has not demonstrated sustained 60 FPS.\n",
            "## Documentation\n",
            "| Guide | Contents |\n| --- | --- |\n"
            "| [Usage](docs/usage.md) | Setup, controls and example workflows |\n"
            "| [Versius preview](docs/versius-recording.md) | Generated instrument motion and placeholder-video scope |\n"
            "| [Repository layout](docs/layout.md) | Local solvers, examples and bundled assets |\n"
            "| [Method](docs/method.md) | Implemented equations, numerical assumptions and gradient limits |\n"
            "| [Papers](docs/papers.md) | Primary sources and implementation mappings |\n"
            "| [Validation](docs/validation.md) | Tests, physical checks, failed comparisons and performance scope |\n"
            "| [Provenance](docs/provenance.md) | Asset attribution and historical versus current evidence |\n"
            "| [Development](docs/development.md) | Documentation generation, recording and contributor commands |\n",
        ]
    )
    if (root / "nsys" / "profile_examples.py").is_file():
        text.extend(
            [
                "## Profiling\n",
                "```bash\n./docker/run.sh --nsys --list\n./docker/run.sh --nsys <example>\n```\n",
                "See [profiling instructions](nsys/README.md) for capture scope and interpretation.\n"
                "Profiler overhead and simulation-time playback must not be reported as live throughput.\n",
            ]
        )
    text.extend(
        [
            "## Check and build\n",
            "```bash\nuv run --locked ruff check .\nuv run --locked ruff format --check .\nuv run --locked python -m unittest discover -s tests -v\nNEWTON_TEST_DEVICE=cuda:0 uv run --locked python -m unittest discover -s tests -v\npython3 tools/build_readme.py --check --require-videos\nuv build\n```\n",
            "Full physical tests can take several minutes. See [validation](docs/validation.md)\n"
            "for measured results and the scope of each check.\n",
        ]
    )
    notices = next((p.name for p in root.glob("THIRD_PARTY_NOTICES*") if p.is_file()), None)
    text.append(
        "License: [Apache-2.0](LICENSE)."
        + (f" Required asset and code attribution: [{notices}]({notices})." if notices else "")
    )
    return "\n".join(text) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if README differs from generated content.")
    parser.add_argument("--require-videos", action="store_true", help="Fail if any discovered example lacks a clip.")
    args = parser.parse_args()
    try:
        result = make_readme(require_videos=args.require_videos)
    except (ValueError, OSError) as error:
        parser.exit(1, f"{error}\n")
    path = ROOT / "README.md"
    if args.check:
        if not path.is_file() or path.read_text() != result:
            parser.exit(1, "README.md is stale; run python3 tools/build_readme.py\n")
        print("README.md is current")
    else:
        path.write_text(result)
        print("Generated README.md")


if __name__ == "__main__":
    main()
